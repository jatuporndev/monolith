/**
 * Tiny i18n layer. English source strings are the keys; Thai lives in TH.
 * Proper nouns (MONOLITH, Echoes of the Colossus, chapter titles, Echo, Colossus,
 * Warden, technical names like FXAA) intentionally stay in English.
 */
export const LANGUAGES = [
  { value: 'en', label: 'English' },
  { value: 'th', label: 'ไทย' },
];

let lang = 'en';
export function getLang() { return lang; }
export function setLang(l) {
  lang = l === 'th' ? 'th' : 'en';
  if (typeof document !== 'undefined') document.documentElement.lang = lang;
}
export function locale() { return lang === 'th' ? 'th-TH' : 'en-GB'; }

/** Translate an English source string; {name} placeholders are filled from vars. */
export function t(s, vars) {
  if (s == null) return s;
  let out = (lang === 'th' && TH[s]) || s;
  if (vars) out = out.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return out;
}

